#!/usr/bin/env python3
"""Ask the local LM Studio chat model (gemma) to turn an architect plan into a plan file.

Part of the project workflow in CLAUDE.md -> "Building a feature". Agent_opus_ARCHITECT
returns a feature plan; this script has gemma lay it out as `plan/feature-<slug>.md` in the
style of an existing plan file and, optionally, list the GitHub issues as `gh` commands.
Mechanical formatting only: gemma must not add, drop or reorder steps, change an executor
tag (QWEN / SONNET / CLAUDE / USER), or touch a spec.

Usage:
    python3 .claude/tools/delegate_doc.py plan <architect_plan.md> [--style plan/03-voice-channel.md] [--model ID]
    python3 .claude/tools/delegate_doc.py issues <architect_plan.md> [--model ID]
    python3 .claude/tools/delegate_doc.py pr <facts.md> [--model ID]
    python3 .claude/tools/delegate_doc.py close <facts.md> [--model ID]

`pr` / `close` (short dev flow, CLAUDE.md -> "Short flow for small changes") turn a facts file
(what changed, why, what was tested and what was NOT, issue number) into a PR body or an
issue-closing comment. gemma only words the facts it is given; Claude checks every claim.

`plan` prints the markdown for the plan file. `issues` prints one `gh issue create ...`
command per issue in the plan's "Issues" section (body via --body, labels/milestone from
the plan). Neither writes or runs anything: Claude reviews the output, saves the file,
and runs the commands (creating issues is outward-facing, so Claude checks each first).
"""
import json
import sys
import urllib.request

import pixel

BASE_URL = "http://localhost:1234/v1"
DEFAULT_MODEL = "google/gemma-4-12b"  # chat model, normally loaded (DEC-32); check `lms ps`
MAX_CHARS = 60_000

SYSTEM_PLAN = """You lay out a feature plan as a plan file for the prototypeRAG repository.

Rules:
- Output ONLY the markdown of the file. No fences around it, no commentary.
- Keep every step, executor tag (QWEN / SONNET / CLAUDE / USER), spec, check, risk and issue from the
  input, in the same order and with the same wording. Do not add, drop, merge or invent any.
- Style: English, concise, tables for comparisons, `- [ ]` checklists for tasks, as in the
  style example. Start with the title line and a one-line summary; keep the section order of
  the input; relative links like [DECISIONS.md](DECISIONS.md) for other plan files.
- Put a `- [ ]` checkbox in front of each step so progress can be ticked off later.
- Specs (for qwen or for Sonnet) go in fenced blocks under their step heading, unchanged.
"""

SYSTEM_ISSUES = """You turn the "Issues" section of a feature plan into GitHub CLI commands.

Rules:
- Output ONLY commands, one per line, nothing else. No fences, no commentary.
- One `gh issue create --title "..." --body "..." --label "area:x" --label "type:y" --milestone "..."`
  per issue, using exactly the title, labels, milestone and body text from the input.
  Escape double quotes inside the body; write a newline in the body as \\n.
- Never add the words "Generated by". If an issue already exists (the input gives #<n>),
  output no command for it.
"""

SYSTEM_PR = """You write a GitHub pull request body from a facts file for the prototypeRAG repository.

Rules:
- Output ONLY the markdown body. No fences, no title line, no commentary.
- Sections: `## What changed` (bullets, file by file), `## Why`, `## Tested` (what was run and
  its result) and `## Not tested` (what was not run). Use only facts from the input; never
  invent a test, result or file. If the input gives an issue number, end with `Fixes #<n>`.
- Never add "Generated by", "Co-Authored-By" or any AI-attribution line.
"""

SYSTEM_CLOSE = """You write a short GitHub issue comment that closes an issue, from a facts file.

Rules:
- Output ONLY the comment text, 2-5 lines, plain markdown. No fences, no commentary.
- State the result plainly: what was done, what was run and its outcome, what was not run,
  and the PR or commit if given. Use only facts from the input; invent nothing.
- Never add "Generated by", "Co-Authored-By" or any AI-attribution line.
"""


def main() -> None:
    args = sys.argv[1:]
    model, style = DEFAULT_MODEL, None
    for flag in ("--model", "--style"):
        if flag in args:
            i = args.index(flag)
            value = args[i + 1]
            del args[i:i + 2]
            if flag == "--model":
                model = value
            else:
                style = value
    if len(args) != 2 or args[0] not in ("plan", "issues", "pr", "close"):
        print(__doc__, file=sys.stderr)
        raise SystemExit(2)
    mode, path = args
    with open(path, encoding="utf-8") as f:
        plan = f.read()[:MAX_CHARS]
    user = f"=== {'facts' if mode in ('pr', 'close') else 'architect plan'} ===\n{plan}"
    if mode == "plan" and style:
        with open(style, encoding="utf-8") as f:
            user += f"\n\n=== style example ({style}, first 120 lines) ===\n" + "".join(f.readlines()[:120])

    body = json.dumps({
        "model": model,
        "messages": [
            {"role": "system", "content": {"plan": SYSTEM_PLAN, "issues": SYSTEM_ISSUES, "pr": SYSTEM_PR, "close": SYSTEM_CLOSE}[mode]},
            {"role": "user", "content": user},
        ],
        "temperature": 0,
        "reasoning_effort": "none",
    }).encode()
    req = urllib.request.Request(
        f"{BASE_URL}/chat/completions", data=body,
        headers={"Content-Type": "application/json"}, method="POST",
    )
    with pixel.agent(model, f"{mode}: format architect plan"), urllib.request.urlopen(req, timeout=300) as resp:
        data = json.load(resp)
    print((data["choices"][0]["message"]["content"] or "").strip())


if __name__ == "__main__":
    main()
